  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'categories' AND policyname = 'pos_anon_categories') THEN
    CREATE POLICY pos_anon_categories ON public.categories FOR ALL USING (true) WITH CHECK (true);
  END IF;

  -- products
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'products' AND policyname = 'pos_anon_products') THEN
