  END IF;

  -- sales
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'sales' AND policyname = 'pos_anon_sales') THEN
    CREATE POLICY pos_anon_sales ON public.sales FOR ALL USING (true) WITH CHECK (true);
  END IF;

  -- sale_items
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'sale_items' AND policyname = 'pos_anon_sale_items') THEN
    CREATE POLICY pos_anon_sale_items ON public.sale_items FOR ALL USING (true) WITH CHECK (true);
  END IF;

  -- invoices
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'invoices' AND policyname = 'pos_anon_invoices') THEN
    CREATE POLICY pos_anon_invoices ON public.invoices FOR ALL USING (true) WITH CHECK (true);
  END IF;

  -- invoice_items
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'invoice_items' AND policyname = 'pos_anon_invoice_items') THEN
    CREATE POLICY pos_anon_invoice_items ON public.invoice_items FOR ALL USING (true) WITH CHECK (true);
  END IF;

  -- payments
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'payments' AND policyname = 'pos_anon_payments') THEN
    CREATE POLICY pos_anon_payments ON public.payments FOR ALL USING (true) WITH CHECK (true);
  END IF;

  -- stock_movements
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'stock_movements' AND policyname = 'pos_anon_stock_movements') THEN
    CREATE POLICY pos_anon_stock_movements ON public.stock_movements FOR ALL USING (true) WITH CHECK (true);
  END IF;

  -- sync_logs
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'sync_logs' AND policyname = 'pos_anon_sync_logs') THEN
    CREATE POLICY pos_anon_sync_logs ON public.sync_logs FOR ALL USING (true) WITH CHECK (true);
  END IF;
END
$$;

