-- ============================================================
-- 1. TABLE : categories
-- Rayons et catégories du catalogue POS (CupSoda, Utensils, etc.)
-- Modèle TypeScript: Category { id, name, icon, sortOrder, color }
-- ============================================================
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    icon VARCHAR(64) DEFAULT 'CupSoda',
    color VARCHAR(64) DEFAULT '#3b82f6',
    parent_id BIGINT DEFAULT 0,
    sort_order INT DEFAULT 0,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_categories_sort_order ON public.categories(sort_order);
CREATE INDEX IF NOT EXISTS idx_categories_is_active ON public.categories(is_active);

-- ============================================================
-- 2. TABLE : products
-- Articles, codes-barres EAN, tarification, stock et seuils d'alerte
-- Modèle TypeScript: Product { id, sku, name, categoryId, price, costPrice, stock, description, taxRate, lowStockThreshold, barcode, imageUrl, isActive }
-- ============================================================
