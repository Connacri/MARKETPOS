-- ============================================================
-- VUE ANALYTIQUE : v_daily_sales_revenue
-- Alignée avec l'interface DailyRevenueStat du Dashboard
-- ============================================================
CREATE OR REPLACE VIEW public.v_daily_sales_revenue AS
SELECT
    to_char(created_at, 'YYYY-MM-DD') AS date,
    to_char(created_at, 'DD/MM/YYYY') AS formatted_date,
    COALESCE(SUM(total_ttc), 0)::NUMERIC(12, 2) AS revenue,
    COALESCE(SUM(subtotal_ht * 0.7), 0)::NUMERIC(12, 2) AS cost,
    COALESCE(SUM(total_ttc - (subtotal_ht * 0.7)), 0)::NUMERIC(12, 2) AS profit,
    COUNT(id)::INT AS orders,
    COALESCE(SUM(jsonb_array_length(items)), COUNT(id))::INT AS units_sold
FROM public.sales
WHERE status = 'COMPLETED'
GROUP BY to_char(created_at, 'YYYY-MM-DD'), to_char(created_at, 'DD/MM/YYYY')
ORDER BY date DESC;

-- ============================================================
-- TRIGGERS : Mise à jour automatique de updated_at
-- ============================================================
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_categories_updated_at ON public.categories;
CREATE TRIGGER trigger_categories_updated_at
BEFORE UPDATE ON public.categories
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

