-- ============================================================
-- POS MODULE PRO - SCHÉMA DE BASE DE DONNÉES CLOUD SUPABASE
-- Script complet de création des tables, index, contraintes et RLS
-- Compatible PostgreSQL 15+ / Supabase Cloud
-- ============================================================

-- Activer les extensions utiles
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================================
-- 1. TABLE : categories
-- Catégories de produits du catalogue POS
-- ============================================================
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    parent_id BIGINT DEFAULT 0,
    sort_order INT DEFAULT 0,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

-- ============================================================
-- 2. TABLE : products
-- Articles, codes-barres EAN, tarification, stock et seuils d'alerte
-- ============================================================
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    cost_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    tax_rate NUMERIC(5, 4) NOT NULL DEFAULT 0.19,
    stock INT NOT NULL DEFAULT 0,
    low_stock_threshold INT NOT NULL DEFAULT 10,
    barcode VARCHAR(64) NOT NULL,
    image_url TEXT,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_products_barcode ON public.products(barcode);
CREATE INDEX IF NOT EXISTS idx_products_sku ON public.products(sku);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category_id);
CREATE INDEX IF NOT EXISTS idx_products_stock ON public.products(stock);

-- ============================================================
-- 3. TABLE : customers
-- Clients particuliers et professionnels
-- ============================================================
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(64),
    email VARCHAR(255),
    address TEXT,
    company VARCHAR(255),
    tax_id VARCHAR(64),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_customers_phone ON public.customers(phone);
CREATE INDEX IF NOT EXISTS idx_customers_name ON public.customers(name);

-- ============================================================
-- 4. TABLE : sales
-- En-têtes de tickets de caisse et ventes
-- ============================================================
CREATE TABLE IF NOT EXISTS public.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_number VARCHAR(64) NOT NULL UNIQUE,
    customer_id BIGINT DEFAULT 0,
    cashier_id BIGINT DEFAULT 0,
    payment_method INT NOT NULL DEFAULT 0, -- 0: Espèces, 1: Carte, 2: Virement, 3: Chèque
    status INT NOT NULL DEFAULT 1,         -- 0: En cours, 1: Payé, 2: Annulé, 3: Remboursé
    discount_total NUMERIC(12, 2) DEFAULT 0,
    total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_sales_sale_number ON public.sales(sale_number);
CREATE INDEX IF NOT EXISTS idx_sales_created_at ON public.sales(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sales_customer ON public.sales(customer_id);

-- ============================================================
-- 5. TABLE : sale_items
-- Lignes d'articles rattachées à une vente POS
-- ============================================================
CREATE TABLE IF NOT EXISTS public.sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES public.sales(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    sku VARCHAR(64) NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    cost_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    tax_rate NUMERIC(5, 4) NOT NULL DEFAULT 0.19,
    quantity INT NOT NULL DEFAULT 1,
    discount NUMERIC(12, 2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sale_items_sale ON public.sale_items(sale_id);
CREATE INDEX IF NOT EXISTS idx_sale_items_product ON public.sale_items(product_id);

-- ============================================================
-- 6. TABLE : invoices
-- Factures formelles éditées pour les clients
-- ============================================================
CREATE TABLE IF NOT EXISTS public.invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(64) NOT NULL UNIQUE,
    sale_id BIGINT DEFAULT 0,
    customer_id BIGINT DEFAULT 0,
    status INT NOT NULL DEFAULT 0, -- 0: Brouillon, 1: Validée, 2: Payée, 3: En retard, 4: Annulée
    discount_total NUMERIC(12, 2) DEFAULT 0,
    company_name VARCHAR(255) DEFAULT 'POS Module Pro',
    company_address TEXT,
    company_tax_id VARCHAR(64),
    due_date TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_invoices_number ON public.invoices(invoice_number);
CREATE INDEX IF NOT EXISTS idx_invoices_created_at ON public.invoices(created_at DESC);

-- ============================================================
-- 7. TABLE : invoice_items
-- Lignes d'articles d'une facture
-- ============================================================
CREATE TABLE IF NOT EXISTS public.invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES public.invoices(id) ON DELETE CASCADE,
    product_id BIGINT,
    description TEXT NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    tax_rate NUMERIC(5, 4) NOT NULL DEFAULT 0.19,
    discount NUMERIC(12, 2) DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_invoice_items_invoice ON public.invoice_items(invoice_id);

-- ============================================================
-- 8. TABLE : payments
-- Enregistrement des règlements (espèces, TPE, chèque, virement)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(12, 2) NOT NULL,
    method INT NOT NULL DEFAULT 0,
    sale_id BIGINT DEFAULT 0,
    invoice_id BIGINT DEFAULT 0,
    reference VARCHAR(128),
    paid_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_payments_sale ON public.payments(sale_id);
CREATE INDEX IF NOT EXISTS idx_payments_invoice ON public.payments(invoice_id);

-- ============================================================
-- 9. TABLE : stock_movements
-- Historique et audit des flux d'inventaire
-- ============================================================
CREATE TABLE IF NOT EXISTS public.stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    change_amount INT NOT NULL,
    reason VARCHAR(64) NOT NULL, -- 'SALE', 'RETURN', 'ADJUSTMENT', 'RESTOCK'
    reference_id VARCHAR(64),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_stock_movements_product ON public.stock_movements(product_id);
CREATE INDEX IF NOT EXISTS idx_stock_movements_created ON public.stock_movements(created_at DESC);

-- ============================================================
-- 10. TABLE : sync_logs
-- Journal d'audit des synchronisations multi-terminaux
-- ============================================================
CREATE TABLE IF NOT EXISTS public.sync_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id VARCHAR(128) NOT NULL,
    sync_type VARCHAR(32) NOT NULL, -- 'PULL', 'PUSH', 'BIDIRECTIONAL'
    status VARCHAR(32) NOT NULL,    -- 'SUCCESS', 'WARNING', 'ERROR'
    items_count INT DEFAULT 0,
    error_message TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sync_logs_created ON public.sync_logs(created_at DESC);

-- ============================================================
-- SÉCURITÉ : Row Level Security (RLS) & Politiques d'Accès
-- ============================================================
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sale_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.invoice_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sync_logs ENABLE ROW LEVEL SECURITY;

-- Politiques ouvertes pour l'authentification standard POS (anon & service_role)
DO $$
BEGIN
