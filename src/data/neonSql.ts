export const NEON_SCHEMA_SQL = `-- ============================================================
-- NEON CLOUD POSTGRESQL - SCHEMA POUR MARKETPOS
-- Compatible Neon Serverless Postgres (Pooler & Direct Connection)
-- ============================================================

-- Extensions PostgreSQL courantes disponibles sur Neon
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ============================================================
-- 1. TABLE : categories
-- Rayons et familles de produits
-- ============================================================
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    icon VARCHAR(64) DEFAULT 'CupSoda',
    color VARCHAR(64) DEFAULT '#3b82f6',
    parent_id BIGINT DEFAULT 0,
    sort_order INT DEFAULT 0,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_neon_categories_sort ON categories(sort_order);
CREATE INDEX IF NOT EXISTS idx_neon_categories_active ON categories(is_active);

-- ============================================================
-- 2. TABLE : products
-- Articles, codes-barres EAN13, tarification DZD et stocks
-- ============================================================
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    cost_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    stock INT NOT NULL DEFAULT 0,
    description TEXT,
    tax_rate NUMERIC(5, 4) NOT NULL DEFAULT 0.19,
    low_stock_threshold INT NOT NULL DEFAULT 10,
    barcode VARCHAR(64) NOT NULL,
    image_url TEXT,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_neon_products_barcode ON products(barcode);
CREATE INDEX IF NOT EXISTS idx_neon_products_sku ON products(sku);
CREATE INDEX IF NOT EXISTS idx_neon_products_cat ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_neon_products_stock ON products(stock);

-- ============================================================
-- 3. TABLE : customers
-- Gestion des clients comptoir et comptes entreprises
-- ============================================================
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(64),
    email VARCHAR(255),
    address TEXT,
    company VARCHAR(255),
    tax_id VARCHAR(64),
    notes TEXT,
    balance_due NUMERIC(12, 2) NOT NULL DEFAULT 0,
    loyalty_points INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_neon_customers_phone ON customers(phone);
CREATE INDEX IF NOT EXISTS idx_neon_customers_name ON customers(name);

-- ============================================================
-- 4. TABLE : sales
-- Journal de caisse, transactions & paiements
-- ============================================================
CREATE TABLE IF NOT EXISTS sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_number VARCHAR(64) NOT NULL UNIQUE,
    customer_id BIGINT DEFAULT 0,
    customer_name VARCHAR(255),
    cashier_id BIGINT DEFAULT 0,
    items JSONB DEFAULT '[]'::jsonb NOT NULL,
    subtotal_ht NUMERIC(12, 2) NOT NULL DEFAULT 0,
    tax_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    discount_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_ttc NUMERIC(12, 2) NOT NULL DEFAULT 0,
    payment_method VARCHAR(32) NOT NULL DEFAULT 'CASH',
    amount_tendered NUMERIC(12, 2) DEFAULT 0,
    change_given NUMERIC(12, 2) DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'COMPLETED',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    sync_status INT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_neon_sales_number ON sales(sale_number);
CREATE INDEX IF NOT EXISTS idx_neon_sales_date ON sales(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_neon_sales_method ON sales(payment_method);
CREATE INDEX IF NOT EXISTS idx_neon_sales_status ON sales(status);

-- ============================================================
-- 5. TABLE : sync_audit_log
-- Traçabilité des synchronisations avec la base locale du POS
-- ============================================================
CREATE TABLE IF NOT EXISTS sync_audit_log (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id VARCHAR(128) NOT NULL,
    direction VARCHAR(32) NOT NULL,
    records_count INT DEFAULT 0,
    details JSONB,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Vue de synthèse pour le tableau de bord
CREATE OR REPLACE VIEW v_daily_revenue_summary AS
SELECT
    DATE_TRUNC('day', created_at) AS sale_date,
    COUNT(id) AS total_sales,
    SUM(total_ttc) AS daily_revenue,
    AVG(total_ttc) AS average_basket,
    SUM(CASE WHEN payment_method = 'CASH' THEN total_ttc ELSE 0 END) AS cash_revenue,
    SUM(CASE WHEN payment_method = 'CARD' THEN total_ttc ELSE 0 END) AS card_revenue
FROM sales
WHERE status = 'COMPLETED'
GROUP BY DATE_TRUNC('day', created_at)
ORDER BY sale_date DESC;
`;

